import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';

const root=path.resolve(import.meta.dirname,'..');
const temp=await fs.mkdtemp(path.join(os.tmpdir(),'lottery-mindmap-'));
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1500,height:1050}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(pathToFileURL(path.join(root,'简单抽奖策划案.html')).href);
  const card=page.locator('[data-graph="M01"]'),stage=card.locator('.graph-stage');
  const source=await page.evaluate(()=>window.lotteryEditor.getGraphs());
  assert.equal(source.M01.presentation,'compact-tree');
  assert.equal(await stage.locator('.node').count(),9);
  assert.equal(await stage.locator('[data-node="root"]>rect').getAttribute('fill'),'#4c72ff');
  assert.equal(await stage.locator('[data-node="access"]>rect').getAttribute('fill'),'#f0f1f3');
  assert.equal(await stage.locator('[data-node="access2"]>rect').getAttribute('fill'),'transparent');
  assert.equal(await stage.locator('[marker-end]').count(),0);
  assert.equal(await page.locator('[data-graph="F01"] [marker-end]').count(),7);
  await card.locator('[data-map-focus]').selectOption('pay');
  assert.equal(await stage.locator('.node').count(),3);
  await card.locator('[data-map-depth]').selectOption('2');
  assert.equal(await stage.locator('.node').count(),2);
  const exported=await page.evaluate(()=>window.planningExport.snapshot());
  assert.equal(exported.planning.diagrams.find(d=>d.kind==='mindmap').sourceData.nodes.length,9);
  await fs.writeFile(path.join(temp,'filtered.html'),exported.html);
  const [download]=await Promise.all([page.waitForEvent('download'),card.locator('[data-map-download]').click()]);
  await download.saveAs(path.join(temp,'branch.svg'));
  const svg=await fs.readFile(path.join(temp,'branch.svg'),'utf8');
  assert.equal((svg.match(/data-node=/g)||[]).length,2);
  assert(svg.includes('消耗与抽取'));
  await card.locator('[data-map-focus]').selectOption('all');
  await card.locator('[data-map-depth]').selectOption('99');
  await stage.locator('[data-node="access"]>rect').click();
  await page.waitForFunction(()=>document.querySelector('[data-map-focus]').value==='access');
  assert.equal(await stage.locator('.node').count(),3);
  // A double click on a branch still opens the editor rather than filtering it away.
  await card.locator('[data-map-focus]').selectOption('all');
  await stage.locator('[data-node="pay"]>rect').dblclick();
  assert.equal(await page.locator('#node-select').inputValue(),'pay');
  assert(await page.locator('#inline-node-text').isVisible());
  assert.equal(await page.locator('#edit-canvas [data-node="root"]>rect').getAttribute('fill'),'#4c72ff');
  await page.locator('#inline-node-text').press('Escape');
  await page.locator('#layout-edit').click();
  await page.locator('#cancel-edit').click();
  await card.locator('[data-map-in]').click();
  const zoomed=Number(await stage.getAttribute('data-scale'));
  await card.locator('[data-map-out]').click();
  assert(Number(await stage.getAttribute('data-scale'))<zoomed);
  await card.locator('[data-map-actual]').click();
  assert.equal(Number(await stage.getAttribute('data-scale')),1);
  await stage.scrollIntoViewIfNeeded();
  const box=await stage.boundingBox();
  await page.mouse.move(box.x+box.width-40,box.y+box.height-40);
  const x=Number(await stage.getAttribute('data-pan-x'));
  await page.mouse.down();await page.mouse.move(box.x+box.width-100,box.y+box.height-70,{steps:4});await page.mouse.up();
  assert(Number(await stage.getAttribute('data-pan-x'))<x);
  await page.mouse.wheel(0,-100);
  await page.waitForFunction(()=>Number(document.querySelector('[data-graph="M01"] .graph-stage').dataset.scale)>1);
  await card.locator('[data-map-width]').click();
  await card.locator('[data-action="zoom"]').click();
  assert(await page.locator('#viewer-body.mindmap-viewport').isVisible());
  await page.locator('#viewer [data-zoom="in"]').click();
  await page.locator('#viewer form button').click();
  await page.goto(pathToFileURL(path.join(temp,'filtered.html')).href);
  assert.equal(await stage.locator('.node').count(),9);
  assert.equal(await card.locator('.mindmap-controls').count(),1);
  assert.equal(await card.locator('[data-map-focus]').inputValue(),'all');
  await page.locator('#section-2').screenshot({path:path.join(import.meta.dirname,'思维导图预览.png')});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
  await card.locator('[data-map-actual]').click();
  assert.equal(Number(await stage.getAttribute('data-scale')),1);
  await card.locator('[data-map-width]').click();
  assert(Number(await stage.getAttribute('data-scale'))<1);
  assert.deepEqual(errors,[]);
  console.log('PASS: shared reading/editing appearance, branch/depth filters, SVG export, full-source save/reopen, pan/wheel/zoom, enlarged view and mobile layout.');
} finally {await browser.close();}
